`timescale 1ns/1ps

module resta_TB;

reg  [15:0] A_in;
reg  [15:0] DR_in;

wire MSB_A;
wire signed [15:0] A;



resta uut (
    .A_in(A_in),
    .DR_in(DR_in),
    .MSB_A(MSB_A),
    .A(A)
);


initial begin



    // ==========================================
    // CASO 1 : 10 - 3 = 7
    // ==========================================
    #10;
    A_in  = 16'd10;
    DR_in = 16'd3;


    // ==========================================
    // CASO 2 : 15 - 15 = 0
    // ==========================================
    #10;
    A_in  = 16'd15;
    DR_in = 16'd15;


    // ==========================================
    // CASO 3 : 5 - 8 = -3
    // ==========================================
    #10;
    A_in  = 16'd5;
    DR_in = 16'd8;


    // ==========================================
    // CASO 4 : 100 - 25 = 75
    // ==========================================
    #10;
    A_in  = 16'd100;
    DR_in = 16'd25;


    // ==========================================
    // CASO 5 : 0 - 1 = -1
    // ==========================================
    #10;
    A_in  = 16'd0;
    DR_in = 16'd1;


    // ==========================================
    // CASO 6 : 32767 - 1
    // ==========================================
    #10;
    A_in  = 16'd32767;
    DR_in = 16'd1;


    // ==========================================
    // FIN
    // ==========================================
    #20;
    $finish;

end


// VCD
initial begin
    $dumpfile("resta_TB.vcd");
    $dumpvars(0, resta_TB);
end

endmodule