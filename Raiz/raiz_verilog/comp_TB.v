`timescale 1ns / 1ps

module comp_TB;

    //====================================================
    // SEÑALES
    //====================================================

    reg [31:0] A;
    reg [31:0] bit1;
    reg [31:0] out_sum;

    wire z;
    wire a_ge_res_bit;

    //====================================================
    // DUT
    //====================================================

    comp DUT(
        .A(A),
        .bit1(bit1),
        .out_sum(out_sum),
        .z(z),
        .a_ge_res_bit(a_ge_res_bit)
    );

    //====================================================
    // TESTS
    //====================================================

    initial begin

        //------------------------------------------------
        // TEST 1 : bit1 == 0
        //------------------------------------------------

        $display("----- TEST 1 : bit1 == 0 -----");

        A     = 32'd20;
        bit1  = 32'd0;
        out_sum  = 32'd15;

        #1;

        if(z == 1'b1)
            $display("PASS");
        else
            $display("FAIL : z incorrect");

    
        //------------------------------------------------
        // TEST 3 : A >= out_sum
        //------------------------------------------------

        $display("----- TEST 3 : A >= out_sum -----");

        A     = 32'd50;
        bit1  = 32'd10;
        out_sum  = 32'd15;

        #1;

        if(a_ge_res_bit == 1'b1)
            $display("PASS");
        else
            $display("FAIL : a_ge_res_bit incorrect");ma

        //------------------------------------------------
        // TEST 4 : A < temp
        //------------------------------------------------

        $display("----- TEST 4 : A < out_sum -----");

        A     = 32'd5;
        bit1  = 32'd1;
        out_sum  = 32'd20;

        #1;

        if(a_ge_res_bit == 1'b0)
            $display("PASS");
        else
            $display("FAIL : a_ge_res_bit incorrect");

        //------------------------------------------------
        // FIN SIMULACIÓN
        //------------------------------------------------

        #2;

        $finish;

    end

    //====================================================
    // WAVEFORMS
    //====================================================

    initial begin
        $dumpfile("comp_TB.vcd");
        $dumpvars(0, comp_TB);
    end

endmodule